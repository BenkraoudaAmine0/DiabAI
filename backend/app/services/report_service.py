YES_NO_KEYS = ("hypertension", "heart_disease", "smoking_history")


def _register_fonts() -> None:
    if FONT in pdfmetrics.getRegisteredFontNames():
        return
    folder = Path(matplotlib.get_data_path()) / "fonts" / "ttf"
    pdfmetrics.registerFont(TTFont(FONT, str(folder / "DejaVuSans.ttf")))
    pdfmetrics.registerFont(TTFont(FONT_BOLD, str(folder / "DejaVuSans-Bold.ttf")))


def _num(value: float, lang: str) -> str:
    text = f"{value:g}"
    return text.replace(".", ",") if lang == "fr" else text


def _pct(prob: float, lang: str) -> str:
    text = format_pct(prob)
    return text.replace(".", ",").replace("%", " %") if lang == "fr" else text


def format_date(iso: Optional[str], lang: str, tz: Optional[str] = None) -> str:
    if not iso:
        return "—"
    try:
        moment = datetime.fromisoformat(str(iso).replace("Z", "+00:00"))
    except ValueError:
        return str(iso)
    try:
        moment = moment.astimezone(ZoneInfo(tz)) if tz else moment.astimezone(timezone.utc)
    except Exception:
        moment = moment.astimezone(timezone.utc)
    if lang == "fr":
        return moment.strftime("%d/%m/%Y à %H:%M")
    return moment.strftime("%b %d, %Y %H:%M").replace(" 0", " ")


def _value_text(item: dict, t: dict, lang: str) -> str:
    key, value = item["key"], item["value"]
    if key == "gender":
        return t["sex"].get(value, str(value))
    if key in ("hypertension", "heart_disease"):
        return t["yes"] if value else t["no"]
    if key == "smoking_history":
        return t["smoking"].get(value, str(value))
    if key == "age":
        return f"{_num(value, lang)} {t['years']}"
    return f"{_num(value, lang)} {item.get('unit') or ''}".strip()


def _flag_text(item: dict, t: dict) -> str:
    if item["status"] == "elevated" and item["key"] in YES_NO_KEYS:
        return t["flags"]["risk"]
    return t["flags"][item["status"]]


def _risk_scale(prob: float, threshold: float, width: float) -> Drawing:
    """Horizontal risk bar with the four tier zones, the threshold tick and
    a marker at the probability."""
    height = 16 * mm
    bar_y, bar_h = 5 * mm, 4 * mm
    d = Drawing(width, height)
    for start, end, color in ZONES:
        d.add(Rect(start * width, bar_y, (end - start) * width, bar_h,
                   fillColor=colors.HexColor(color), strokeColor=None))
    tx = threshold * width
    d.add(Line(tx, bar_y - 1.5 * mm, tx, bar_y + bar_h + 1.5 * mm,
               strokeColor=INK, strokeWidth=0.8, strokeDashArray=[2, 1.5]))
    x = min(max(prob, 0.0), 1.0) * width
    top = bar_y + bar_h + 1 * mm
    d.add(Polygon([x - 2.2 * mm, top + 3.2 * mm, x + 2.2 * mm, top + 3.2 * mm, x, top],
                  fillColor=INK, strokeColor=None))
    for value in (0, 0.3, 0.5, 0.75, 1.0):
        anchor = "start" if value == 0 else "end" if value == 1 else "middle"
        d.add(String(value * width, 0, f"{int(value * 100)}%", fontName=FONT,
                     fontSize=6.5, fillColor=MUTED, textAnchor=anchor))
    return d


def build_pdf(
    record: dict,
    *,
    patient: dict,
    doctor_name: Optional[str],
    reviewer_name: Optional[str],
    values: list[dict],
    threshold: float,
    waterfall_png: Optional[bytes],
    lang: str = "en",
    tz: Optional[str] = None,
) -> bytes:
    _register_fonts()
    t = TEXT["fr" if lang == "fr" else "en"]
    lang = "fr" if lang == "fr" else "en"

    base = ParagraphStyle("base", fontName=FONT, fontSize=9, leading=12.5, textColor=INK)
    small = ParagraphStyle("small", parent=base, fontSize=7.5, leading=10, textColor=MUTED)
    h1 = ParagraphStyle("h1", parent=base, fontName=FONT_BOLD, fontSize=15, leading=19)
    h2 = ParagraphStyle("h2", parent=base, fontName=FONT_BOLD, fontSize=10.5, leading=14,
                        spaceBefore=9, spaceAfter=4)
    big = ParagraphStyle("big", parent=base, fontName=FONT_BOLD, fontSize=22, leading=26)
    bold = ParagraphStyle("bold", parent=base, fontName=FONT_BOLD)

    def p(text: str, style: ParagraphStyle = base) -> Paragraph:
        return Paragraph(escape(str(text)).replace("\n", "<br/>"), style)

    page_w, _ = A4
    margin = 16 * mm
    width = page_w - 2 * margin
    story: list = []

    # ── header ──
    brand = ParagraphStyle("brand", parent=bold, fontSize=13, textColor=TEAL)
    header = Table(
        [[p("DiabAI", brand), p(f"{t['generated']} {format_date(datetime.now(timezone.utc).isoformat(), lang, tz)}", small)]],
        colWidths=[width * 0.5, width * 0.5],
    )
    header.setStyle(TableStyle([("ALIGN", (1, 0), (1, 0), "RIGHT"),
                                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                                ("LINEBELOW", (0, 0), (-1, 0), 1.2, TEAL),
                                ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))
    story += [header, Spacer(1, 6 * mm), p(t["title"], h1), p(t["subtitle"], small),
              Spacer(1, 4 * mm)]

    # ── patient ──
    inp = record.get("input") or {}
    sex = t["sex"].get(str(inp.get("gender", "")).lower(), "—")
    age = f"{_num(float(inp.get('age', 0)), lang)} {t['years']}" if inp.get("age") is not None else "—"
    info_rows = [
        [p(t["patient"], small), p(patient.get("full_name") or "—", bold),
         p(t["assessed"], small), p(format_date(record.get("created_at"), lang, tz))],
        [p(t["sex_age"], small), p(f"{sex} · {age}"),
         p(t["doctor"], small), p(doctor_name or "—")],
        [p(t["email"], small), p(patient.get("email") or "—"),
         p(t["record"], small), p(str(record.get("id", ""))[:8].upper())],
    ]
    info = Table(info_rows, colWidths=[width * 0.14, width * 0.36, width * 0.18, width * 0.32])
    info.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), SOFT),
                              ("BOX", (0, 0), (-1, -1), 0.6, LINE),
                              ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                              ("TOPPADDING", (0, 0), (-1, -1), 4),
                              ("BOTTOMPADDING", (0, 0), (-1, -1), 4)]))
    story += [info]

    # ── result ──
    prob = float(record.get("probability") or 0)
    label_key = "Diabetic" if record.get("prediction") == 1 else "Non-Diabetic"
    tier_key = str(record.get("risk_tier", "")).replace("⚠️", "").strip()
    status = record.get("status") or "pending"
    status_text = t["statuses"].get(status, status)
    if status != "pending" and record.get("reviewed_at"):
        status_text += " " + t["by"].format(
            name=reviewer_name or "—", date=format_date(record.get("reviewed_at"), lang, tz)
        )
    label_color = STATUS_COLORS["high"] if label_key == "Diabetic" else STATUS_COLORS["normal"]
    result = Table(
        [
            [p(t["probability"], small), p(t["tier"], small), p(t["status"], small)],
            [p(_pct(prob, lang), big),
             p(t["tiers"].get(tier_key, tier_key), ParagraphStyle("tier", parent=bold, fontSize=12, leading=15)),
             p(status_text, bold)],
            [p(f"{t['labels'][label_key]} · {t['threshold']} {_pct(threshold, lang)}",
               ParagraphStyle("lbl", parent=bold, textColor=label_color)), "", ""],
        ],
        colWidths=[width * 0.36, width * 0.24, width * 0.40],
    )
    result.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"),
                                ("SPAN", (0, 2), (-1, 2)),
                                ("LEFTPADDING", (0, 0), (-1, -1), 0)]))
    story += [p(t["result"], h2), result, Spacer(1, 2 * mm), _risk_scale(prob, threshold, width)]

    # ── clinical values ──
    rows = [[p(t["parameter"], bold), p(t["value"], bold), p(t["reference"], bold), p(t["flag"], bold)]]
    for item in values:
        flag_style = ParagraphStyle(f"f-{item['key']}", parent=bold,
                                    textColor=STATUS_COLORS[item["status"]])
        rows.append([p(t["params"].get(item["key"], item["key"])), p(_value_text(item, t, lang)),
                     p(t["refs"].get(item["key"], "—"), small), p(_flag_text(item, t), flag_style)])
    table = Table(rows, colWidths=[width * 0.28, width * 0.24, width * 0.28, width * 0.20], repeatRows=1)
    table.setStyle(TableStyle([("LINEBELOW", (0, 0), (-1, 0), 0.8, INK),
                               ("LINEBELOW", (0, 1), (-1, -1), 0.4, LINE),
                               ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                               ("TOPPADDING", (0, 0), (-1, -1), 3),
                               ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]))
    story += [KeepTogether([p(t["values"], h2), table])]

    # ── factors ──
    by_key = {v["key"]: v for v in values}
    rows = [[p(t["factor"], bold), p(t["value"], bold), p(t["impact"], bold), p(t["effect"], bold)]]
    for f in (record.get("top_factors") or [])[:5]:
        up = float(f["value"]) > 0
        effect_style = ParagraphStyle(f"e-{f['feature']}", parent=base,
                                      textColor=STATUS_COLORS["high" if up else "normal"])
        item = by_key.get(f["feature"])
        rows.append([p(t["params"].get(f["feature"], f["feature"])),
                     p(_value_text(item, t, lang) if item else "—"),
                     p(f"{float(f['value']):+.2f}".replace(".", "," if lang == "fr" else ".")),
                     p(t["up"] if up else t["down"], effect_style)])
    table = Table(rows, colWidths=[width * 0.28, width * 0.24, width * 0.16, width * 0.32], repeatRows=1)
    table.setStyle(TableStyle([("LINEBELOW", (0, 0), (-1, 0), 0.8, INK),
                               ("LINEBELOW", (0, 1), (-1, -1), 0.4, LINE),
                               ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                               ("TOPPADDING", (0, 0), (-1, -1), 3),
                               ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]))
    story += [KeepTogether([p(t["factors"], h2), table])]

    # ── interpretation ──
    interpretation = (record.get("interpretation") or "").strip()
    box = Table([[p(interpretation or t["no_interpretation"])],
                 [p(t["ai_note"], small)]], colWidths=[width])
    box.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), SOFT),
                             ("BOX", (0, 0), (-1, -1), 0.6, LINE),
                             ("LEFTPADDING", (0, 0), (-1, -1), 8),
                             ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                             ("TOPPADDING", (0, 0), (-1, -1), 5),
                             ("BOTTOMPADDING", (0, 0), (-1, -1), 5)]))
    story += [KeepTogether([p(t["interpretation"], h2), box])]

    # ── review ──
    review = [p(status_text, bold)]
    if record.get("review_note"):
        review.append(p(f"{t['note']} : {record['review_note']}" if lang == "fr"
                        else f"{t['note']}: {record['review_note']}"))
    story += [KeepTogether([p(t["review"], h2), *review])]

    # ── SHAP waterfall ──
    if waterfall_png:
        try:
            img = Image(io.BytesIO(waterfall_png))
            scale = min(1.0, (width * 0.92) / img.imageWidth)
            img.drawWidth = img.imageWidth * scale
            img.drawHeight = img.imageHeight * scale
            story += [KeepTogether([p(t["waterfall"], h2), img])]
        except Exception:
            pass  # a broken image must not block the report

    def footer(canvas, doc) -> None:
        canvas.saveState()
        canvas.setStrokeColor(LINE)
        canvas.line(margin, 14 * mm, page_w - margin, 14 * mm)
        text = canvas.beginText(margin, 10 * mm)
        text.setFont(FONT, 6.8)
        text.setFillColor(MUTED)
        for line in simpleSplit(t["disclaimer"], FONT, 6.8, width - 22 * mm):
            text.textLine(line)
        canvas.drawText(text)
        canvas.setFont(FONT, 7)
        canvas.drawRightString(page_w - margin, 10 * mm, f"{t['page']} {doc.page}")
        canvas.restoreState()

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4, leftMargin=margin, rightMargin=margin,
        topMargin=14 * mm, bottomMargin=20 * mm,
        title=f"DiabAI — {t['title']}", author="DiabAI",
    )
    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()
